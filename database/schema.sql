-- PostgreSQL Schema for University Budget Management System
-- Compatible with PostgreSQL 13+ (including Neon Serverless PostgreSQL)

-- Drop existing tables if re-initializing (in reverse foreign key order)
DROP TABLE IF EXISTS expenditures CASCADE;
DROP TABLE IF EXISTS sub_heads CASCADE;
DROP TABLE IF EXISTS main_heads CASCADE;
DROP TABLE IF EXISTS goals CASCADE;
DROP TABLE IF EXISTS departments CASCADE;

-- 1. Departments Table
CREATE TABLE departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

-- 2. Goals Table (Annual Budget Goals)
CREATE TABLE goals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    description TEXT NOT NULL
);

-- 3. Main Heads Table
CREATE TABLE main_heads (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00
);

-- 4. Sub Heads Table
CREATE TABLE sub_heads (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    main_head_id INTEGER NOT NULL REFERENCES main_heads(id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL,
    description TEXT NOT NULL
);

-- 5. Expenditures Table
CREATE TABLE expenditures (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE RESTRICT,
    sub_head_id INTEGER NOT NULL REFERENCES sub_heads(id) ON DELETE RESTRICT,
    department_id INTEGER NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    type VARCHAR(20) NOT NULL CHECK (type IN ('Consumable', 'Non-Consumable')),
    amount NUMERIC(10, 2) NOT NULL,
    date DATE NOT NULL,
    description TEXT NOT NULL,
    cheque_number VARCHAR(50) NOT NULL,
    bill_number VARCHAR(100) NOT NULL
);

-- Performance & Foreign Key Indexes
CREATE INDEX idx_main_heads_goal_id ON main_heads(goal_id);
CREATE INDEX idx_sub_heads_main_head_id ON sub_heads(main_head_id);
CREATE INDEX idx_expenditures_goal_id ON expenditures(goal_id);
CREATE INDEX idx_expenditures_sub_head_id ON expenditures(sub_head_id);
CREATE INDEX idx_expenditures_department_id ON expenditures(department_id);
CREATE INDEX idx_expenditures_date ON expenditures(date);
CREATE INDEX idx_expenditures_bill_number ON expenditures(bill_number);
